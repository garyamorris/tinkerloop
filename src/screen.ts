import { emitKeypressEvents } from "node:readline";
import type { Key } from "node:readline";
import { stripVTControlCharacters } from "node:util";
import { cleanText, literalText, paint } from "./render.js";

export function supportsScreen(plain = false): boolean {
  return (
    !plain &&
    Boolean(
      process.stdin.isTTY && process.stdout.isTTY && process.stderr.isTTY,
    ) &&
    process.env.TERM !== "dumb"
  );
}

// The screen is just a view and a small input editor. It never calls a model.
// Full-screen mode uses the alternate terminal buffer, restored by close().
interface InputPrompt {
  kind: "chat" | "wait" | "text" | "secret" | "choice" | "approval";
  title: string;
  description: string;
  value: string[];
  cursor: number;
  defaultValue: string;
  choices: string[];
  selected: number;
  resolve(value: string): void;
  reject(error: unknown): void;
  cleanup(): void;
}

function charWidth(character: string): number {
  if (/[\p{Mark}\u200d\ufe0f]/u.test(character)) return 0;
  const point = character.codePointAt(0)!;
  return /\p{Extended_Pictographic}/u.test(character) ||
    (point >= 0x1100 &&
      (point <= 0x115f ||
        (point >= 0x2e80 && point <= 0xa4cf) ||
        (point >= 0xac00 && point <= 0xd7a3) ||
        (point >= 0xff01 && point <= 0xff60) ||
        point >= 0x20000))
    ? 2
    : 1;
}

// Preserve only styles generated by our renderer, and never split an ANSI code.
export function fitScreenLine(text: string, columns: number): string {
  let output = "";
  let width = 0;
  for (const token of text.match(/\x1b\[[0-9;]*m|[^]/gu) ?? []) {
    if (/^\x1b\[[0-9;]*m$/.test(token)) {
      output += token;
      continue;
    }
    if (/[\x00-\x1f\x7f-\x9f]/.test(token)) continue;
    const size = charWidth(token);
    if (width + size > columns) break;
    output += token;
    width += size;
  }
  return output + " ".repeat(Math.max(0, columns - width));
}

export function wrapScreenLine(text: string, columns: number): string[] {
  columns = Math.max(1, columns);
  const result: string[] = [];
  let line = "";
  let width = 0;
  for (const character of Array.from(
    cleanText(text).replaceAll("\n", " ").replaceAll("\t", "  "),
  )) {
    const size = charWidth(character);
    if (width + size > columns) {
      result.push(line);
      line = "";
      width = 0;
    }
    line += character;
    width += size;
  }
  result.push(line);
  return result;
}

export function createScreen(
  cancel: () => void,
  options: {
    input?: NodeJS.ReadStream;
    output?: NodeJS.WriteStream;
    env?: NodeJS.ProcessEnv;
  } = {},
) {
  const input = options.input ?? process.stdin;
  const output = options.output ?? process.stdout;
  const previousRaw = input.isRaw;
  const color = !Object.hasOwn(options.env ?? process.env, "NO_COLOR");
  const accent = (text: string) => paint(text, "1;36", color);
  const muted = (text: string) => paint(text, "90", color);
  const transcript: string[] = [];
  const history: string[] = [];
  let historyIndex = 0;
  let header = ["<> Tinkerloop", "Guided setup"];
  let footer = ["No model requests yet."];
  let status = "Ready";
  let prompt: InputPrompt | undefined;
  let scroll = 0;
  let closed = false;
  let pasting = false;
  let scheduled = false;
  let pendingText = "";
  const columns = () => Math.max(1, output.columns || 80);
  const rows = () => Math.max(1, output.rows || 24);

  function redraw(): void {
    if (closed) return;
    const width = columns();
    const height = rows();
    if (width < 30 || height < 12) {
      output.write(
        "\x1b[?25l\x1b[H\x1b[2J" +
          fitScreenLine("Enlarge terminal (30x12)", width),
      );
      return;
    }
    const divider = muted("─".repeat(width));
    let body: string[];
    if (prompt && !["chat", "wait"].includes(prompt.kind)) {
      body = [
        accent(`  ${prompt.title}`),
        "",
        ...prompt.description
          .split("\n")
          .flatMap((line) =>
            wrapScreenLine(line, width - 4).map((part) => "  " + part),
          ),
        "",
      ];
      if (prompt.kind === "choice")
        body.push(
          ...prompt.choices.map((choice, index) =>
            index === prompt!.selected
              ? accent(`  › ${index + 1}. ${choice}`)
              : `    ${index + 1}. ${choice}`,
          ),
        );
    } else
      body = transcript.flatMap((line) => {
        const plain = stripVTControlCharacters(line);
        return Array.from(plain).reduce(
          (sum, char) => sum + charWidth(char),
          0,
        ) <= width
          ? [line]
          : wrapScreenLine(plain, width);
      });

    const metricLines = footer
      .flatMap((line) =>
        wrapScreenLine(cleanText(line), width - 2).map((part) =>
          muted(" " + part),
        ),
      )
      .slice(0, 3);
    const controls =
      prompt?.kind === "wait"
        ? " Enter exit · PgUp/PgDn scroll · Ctrl+C quit"
        : prompt?.kind === "choice"
          ? " ↑/↓ or 1–9 choose · Enter confirm · Ctrl+C quit"
          : prompt?.kind === "approval"
            ? " y approve · n or Enter deny · PgUp/PgDn review · Ctrl+C quit"
            : prompt && prompt.kind !== "chat"
              ? " Enter confirm · Ctrl+U clear · Ctrl+C quit"
              : " Enter send · ↑/↓ history · PgUp/PgDn scroll · Ctrl+C quit";
    const bottom = [
      divider,
      ...metricLines,
      muted(` ${status}`),
      "",
      muted(controls),
    ];
    const top = [accent(" " + header[0]), muted(" " + header[1]), divider];
    const available = Math.max(1, height - top.length - bottom.length);
    if (prompt?.kind === "choice") {
      const selectedRow = body.length - prompt.choices.length + prompt.selected;
      if (selectedRow < scroll) scroll = selectedRow;
      if (selectedRow >= scroll + available)
        scroll = selectedRow - available + 1;
    }
    scroll = Math.max(
      0,
      Math.min(scroll, Math.max(0, body.length - available)),
    );
    // Forms start at the top; the transcript follows the newest output.
    const end =
      prompt && !["chat", "wait"].includes(prompt.kind)
        ? Math.min(body.length, available + scroll)
        : Math.max(0, body.length - scroll);
    const start =
      prompt && !["chat", "wait"].includes(prompt.kind)
        ? scroll
        : Math.max(0, end - available);
    const visible = body.slice(start, end);
    while (visible.length < available) visible.push("");
    if (body.length > available)
      bottom[bottom.length - 1] = muted(
        `${controls} · ${start + 1}–${Math.min(end, body.length)}/${body.length}`,
      );

    let cursorColumn = 4;
    let inputLine = "";
    if (prompt?.kind === "wait") inputLine = " Press Enter to exit";
    else if (prompt && prompt.kind !== "choice" && prompt.kind !== "approval") {
      const hidden = prompt.kind === "secret";
      const characters = prompt.value.map((character) =>
        hidden
          ? "•"
          : character === "\n"
            ? "↵"
            : character === "\t"
              ? "→"
              : character,
      );
      let from = 0;
      const room = Math.max(4, width - 6);
      while (
        characters
          .slice(from, prompt.cursor)
          .reduce((sum, char) => sum + charWidth(char), 0) >= room
      )
        from++;
      const before = characters.slice(from, prompt.cursor).join("");
      const value = characters.slice(from).join("");
      inputLine = accent(" › ") + (value || muted(prompt.defaultValue));
      cursorColumn =
        4 + Array.from(before).reduce((sum, char) => sum + charWidth(char), 0);
    } else if (prompt?.kind === "choice")
      inputLine = " Enter selects the highlighted provider";
    else if (prompt?.kind === "approval")
      inputLine = " Allow this action? [y/N]";
    else inputLine = " Working…";
    bottom[bottom.length - 2] = inputLine;
    const all = [...top, ...visible, ...bottom].slice(0, height);
    while (all.length < height) all.push("");
    // Do not print a newline on the last row: that would scroll the screen.
    output.write(
      "\x1b[?25l\x1b[H" +
        all.map((line) => fitScreenLine(line, width) + "\x1b[0m").join("\r\n"),
    );
    if (prompt && !["choice", "approval", "wait"].includes(prompt.kind)) {
      output.write(
        `\x1b[${height - 1};${Math.min(cursorColumn, width)}H\x1b[?25h`,
      );
    }
  }

  function schedule(): void {
    if (scheduled || closed) return;
    scheduled = true;
    setImmediate(() => {
      scheduled = false;
      redraw();
    });
  }

  function complete(value: string): void {
    const active = prompt;
    if (!active) return;
    prompt = undefined;
    active.cleanup();
    active.value.fill(""); // Do not retain an API key in the screen state.
    active.resolve(value);
    scroll = 0;
    schedule();
  }

  function keypress(text: string | undefined, key: Key): void {
    if (key.ctrl && key.name === "c") {
      cancel();
      return;
    }
    if (key.name === "paste-start") {
      pasting = true;
      return;
    }
    if (key.name === "paste-end") {
      pasting = false;
      schedule();
      return;
    }
    if (!pasting && (key.name === "pageup" || key.name === "pagedown")) {
      const direction = key.name === "pageup" ? 1 : -1;
      scroll +=
        (prompt && !["chat", "wait"].includes(prompt.kind)
          ? -direction
          : direction) * Math.max(1, rows() - 10);
      schedule();
      return;
    }
    if (!prompt) return;
    // Pasted text can fill an editor, but must never approve an action or select a provider.
    if (pasting && ["choice", "approval", "wait"].includes(prompt.kind)) return;
    if (prompt.kind === "wait") {
      if (key.name === "return") complete("");
      return;
    } else if (prompt.kind === "choice") {
      if (key.name === "up")
        prompt.selected =
          (prompt.selected + prompt.choices.length - 1) % prompt.choices.length;
      else if (key.name === "down")
        prompt.selected = (prompt.selected + 1) % prompt.choices.length;
      else if (
        text &&
        /^[1-9]$/.test(text) &&
        Number(text) <= prompt.choices.length
      )
        prompt.selected = Number(text) - 1;
      else if (key.name === "return") {
        complete(String(prompt.selected));
        return;
      }
    } else if (prompt.kind === "approval") {
      if (text?.toLowerCase() === "y") {
        complete("yes");
        return;
      }
      if (text?.toLowerCase() === "n" || key.name === "return") {
        complete("no");
        return;
      }
    } else if (!pasting && key.name === "return") {
      const value = prompt.value.join("") || prompt.defaultValue;
      if (prompt.kind === "chat" && value.trim()) {
        history.push(value);
        historyIndex = history.length;
      }
      complete(value);
      return;
    } else if (
      !pasting &&
      key.ctrl &&
      key.name === "d" &&
      !prompt.value.length
    ) {
      if (prompt.kind === "chat") complete("/exit");
      else cancel();
      return;
    } else if (!pasting && key.ctrl && key.name === "u") {
      prompt.value = [];
      prompt.cursor = 0;
    } else if (!pasting && key.name === "backspace") {
      if (prompt.cursor > 0) prompt.value.splice(--prompt.cursor, 1);
    } else if (!pasting && key.name === "delete")
      prompt.value.splice(prompt.cursor, 1);
    else if (!pasting && key.name === "left")
      prompt.cursor = Math.max(0, prompt.cursor - 1);
    else if (!pasting && key.name === "right")
      prompt.cursor = Math.min(prompt.value.length, prompt.cursor + 1);
    else if (
      !pasting &&
      (key.name === "home" || (key.ctrl && key.name === "a"))
    )
      prompt.cursor = 0;
    else if (!pasting && (key.name === "end" || (key.ctrl && key.name === "e")))
      prompt.cursor = prompt.value.length;
    else if (
      !pasting &&
      prompt.kind === "chat" &&
      ["up", "down"].includes(key.name ?? "")
    ) {
      historyIndex = Math.max(
        0,
        Math.min(history.length, historyIndex + (key.name === "up" ? -1 : 1)),
      );
      prompt.value = Array.from(history[historyIndex] ?? "");
      prompt.cursor = prompt.value.length;
    } else if (
      pasting ||
      (key.ctrl && key.name === "j") ||
      (text && !key.ctrl && !key.meta && !text.startsWith("\x1b"))
    ) {
      const value = key.ctrl && key.name === "j" ? "\n" : cleanText(text ?? "");
      const characters = Array.from(value).slice(
        0,
        Math.max(0, 100_000 - prompt.value.length),
      );
      prompt.value.splice(prompt.cursor, 0, ...characters);
      prompt.cursor += characters.length;
    }
    schedule();
  }

  emitKeypressEvents(input);
  input.setRawMode(true);
  input.resume();
  input.on("keypress", keypress);
  input.once("end", cancel);
  input.once("error", cancel);
  output.on("resize", schedule);
  output.write("\x1b[?1049h\x1b[?2004h\x1b[?25l");
  redraw();

  function ask(
    kind: InputPrompt["kind"],
    title: string,
    description: string,
    signal: AbortSignal,
    defaultValue = "",
    choices: string[] = [],
  ): Promise<string> {
    signal.throwIfAborted();
    if (prompt) throw new Error("A terminal question is already open.");
    return new Promise((resolve, reject) => {
      const abort = () => {
        if (prompt) {
          const active = prompt;
          prompt = undefined;
          active.cleanup();
          active.value.fill("");
          reject(signal.reason);
        }
      };
      prompt = {
        kind,
        title,
        description,
        defaultValue,
        choices,
        value: [],
        cursor: 0,
        selected: 0,
        resolve,
        reject,
        cleanup: () => signal.removeEventListener("abort", abort),
      };
      signal.addEventListener("abort", abort, { once: true });
      scroll = 0;
      schedule();
    });
  }

  return {
    write(text: string): void {
      pendingText += text;
      const parts = pendingText.split("\n");
      pendingText = parts.pop()!;
      transcript.push(...parts);
      // Bound view memory; conversation memory is managed by the harness.
      if (transcript.length > 5000)
        transcript.splice(0, transcript.length - 5000);
      scroll = 0;
      schedule();
    },
    setHeader(lines: string[]): void {
      header = lines.map(cleanText);
      schedule();
    },
    setFooter(lines: string[]): void {
      footer = lines.map(cleanText);
      schedule();
    },
    setStatus(value: string): void {
      status = cleanText(value);
      schedule();
    },
    read(signal: AbortSignal): Promise<string> {
      status = "Ready";
      return ask("chat", "You", "", signal);
    },
    wait(message: string, signal: AbortSignal): Promise<string> {
      status = message;
      return ask("wait", "", "", signal);
    },
    choose(
      title: string,
      choices: string[],
      signal: AbortSignal,
    ): Promise<number> {
      return ask(
        "choice",
        title,
        "Choose a model provider. Use the arrow keys or a number, then press Enter.",
        signal,
        "",
        choices,
      ).then(Number);
    },
    ask(
      title: string,
      description: string,
      defaultValue: string,
      signal: AbortSignal,
      secret = false,
    ): Promise<string> {
      return ask(
        secret ? "secret" : "text",
        title,
        description,
        signal,
        defaultValue,
      );
    },
    confirm(preview: string, signal: AbortSignal): Promise<boolean> {
      return ask(
        "approval",
        "Approval required",
        literalText(preview),
        signal,
      ).then((answer) => answer === "yes");
    },
    close(): void {
      if (closed) return;
      closed = true;
      if (prompt) {
        prompt.cleanup();
        prompt.value.fill("");
        prompt.reject(new Error("Terminal closed."));
        prompt = undefined;
      }
      input.removeListener("keypress", keypress);
      input.removeListener("end", cancel);
      input.removeListener("error", cancel);
      output.removeListener("resize", schedule);
      input.setRawMode(Boolean(previousRaw));
      input.pause();
      output.write("\x1b[?2004l\x1b[0m\x1b[?25h\x1b[?1049l");
    },
  };
}

export type Screen = ReturnType<typeof createScreen>;
